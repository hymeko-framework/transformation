//! A checked, transient canonical projection of the owner's nonlinear mechanism.
//! No integration or independently maintained physical state lives here.
use super::*;
use hymeko_geometry::JointType;
use hymeko_numerics::{Interconnection, Port as SignedPort};

/// Numerical values of the canonical pH representation at one engine state.
/// Ordering is [q,p] over `slots`; fixed coordinates are excluded. `gradient`
/// uses central differences of the owner's H at fixed momentum. The smooth rate
/// excludes contact impulses, which belong to the separate discrete energy audit.
#[derive(Clone, Debug, serde::Serialize)]
pub struct MechanicalProjection {
    pub slots: Vec<usize>,
    pub declarations: Vec<Option<DeclId>>,
    pub names: Vec<String>,
    pub q: Vec<f64>,
    pub p: Vec<f64>,
    pub gradient: Vec<f64>,
    pub smooth_rate: Vec<f64>,
    /// Row-major J. Generated by the existing Tensor signed interconnection.
    pub interconnection: Vec<f64>,
    /// Lower-block diagonal of R; upper block is zero.
    pub damping: Vec<f64>,
    /// Generalized applied force u; G=[0;I] and y=partial H/partial p.
    pub input: Vec<f64>,
    pub energy: f64,
    pub input_power: f64,
    pub dissipated_power: f64,
    pub balance_residual: f64,
    pub velocity_residual: f64,
}

impl MechanicalProjection {
    /// Observe a finite regular mechanism of 1..64 slots without modifying it.
    /// The owner's articulated inertia-floor rejection is retained. Nonfinite,
    /// singular, unsupported-axis and dimension failures are explicit errors.
    pub fn observe(engine: &Engine) -> Result<Self, String> {
        let plan = engine.dynamics();
        let nslots = plan.slots();
        if nslots == 0
            || nslots > 64
            || engine.q.len() != nslots
            || engine.qd.len() != nslots
            || engine.torque.len() != nslots
            || engine
                .q
                .iter()
                .chain(&engine.qd)
                .chain(&engine.torque)
                .any(|x| !x.is_finite())
        {
            return Err("canonical mechanics requires 1..64 finite joint slots".into());
        }
        let slots: Vec<_> = engine
            .model()
            .joints
            .iter()
            .enumerate()
            .filter(|(_, j)| j.joint_type != JointType::Fixed)
            .map(|(i, _)| i)
            .collect();
        let n = slots.len();
        if n == 0 || n != plan.movable() {
            return Err("unsupported or absent moving coordinates".into());
        }
        let zero = vec![0.; nslots];
        let mut momentum = zero.clone();
        plan.inverse_dynamics(
            engine.model(),
            &engine.q,
            &zero,
            &engine.qd,
            [0.; 3],
            &mut plan.scratch(),
            &mut momentum,
        );
        let velocity = plan
            .solve_mass(engine.model(), &engine.q, &momentum)
            .ok_or("singular articulated mass operator")?;
        let velocity_residual = velocity
            .iter()
            .zip(&engine.qd)
            .map(|(a, b)| (a - b).abs())
            .fold(0., f64::max);
        if velocity_residual > 1e-8 * (1. + engine.qd.iter().map(|x| x.abs()).fold(0., f64::max)) {
            return Err("momentum/velocity round trip failed".into());
        }
        let energy = engine
            .energy_at(&engine.q, &velocity)
            .ok_or("invalid physical Hamiltonian")?;
        let mut gradient = vec![0.; 2 * n];
        for (i, &slot) in slots.iter().enumerate() {
            let step = 1e-5 * engine.q[slot].abs().max(1.);
            let mut endpoints = [0.; 2];
            for (side, sign) in [-1., 1.].into_iter().enumerate() {
                let mut q = engine.q.clone();
                q[slot] += sign * step;
                let v = plan
                    .solve_mass(engine.model(), &q, &momentum)
                    .ok_or("singular coordinate neighbourhood")?;
                endpoints[side] = engine
                    .energy_at(&q, &v)
                    .ok_or("invalid Hamiltonian neighbourhood")?;
            }
            gradient[i] = (endpoints[1] - endpoints[0]) / (2. * step);
            gradient[n + i] = velocity[slot];
        }
        let interconnection = Interconnection::new(
            2 * n,
            (0..n).map(|i| SignedPort::edge(i, n + i, 1.)).collect(),
        );
        let mut smooth_rate = vec![0.; 2 * n];
        interconnection.apply(&gradient, &mut smooth_rate);
        let damping: Vec<_> = slots
            .iter()
            .map(|&i| engine.damping_at(i).ok_or("invalid viscous coefficient"))
            .collect::<Result<_, _>>()?;
        let input: Vec<_> = slots.iter().map(|&i| engine.torque[i]).collect();
        let mut input_power = 0.;
        let mut dissipated_power = 0.;
        for i in 0..n {
            smooth_rate[n + i] += input[i] - damping[i] * gradient[n + i];
            input_power += input[i] * gradient[n + i];
            dissipated_power += damping[i] * gradient[n + i].powi(2);
        }
        let balance_residual = gradient
            .iter()
            .zip(&smooth_rate)
            .map(|(e, f)| e * f)
            .sum::<f64>()
            - input_power
            + dissipated_power;
        let out = Self {
            declarations: slots
                .iter()
                .map(|&i| {
                    let id = engine.model().joints[i].did;
                    (!id.is_none()).then_some(id)
                })
                .collect(),
            names: slots
                .iter()
                .map(|&i| engine.model().joints[i].name.clone())
                .collect(),
            q: slots.iter().map(|&i| engine.q[i]).collect(),
            p: slots.iter().map(|&i| momentum[i]).collect(),
            slots,
            gradient,
            smooth_rate,
            interconnection: interconnection.dense(),
            damping,
            input,
            energy,
            input_power,
            dissipated_power,
            balance_residual,
            velocity_residual,
        };
        out.validate()?;
        Ok(out)
    }

    /// Validate the complete canonical structure, dimensions and power identity.
    /// This detects corrupted projections; it is not an independent check of H.
    pub fn validate(&self) -> Result<(), String> {
        let n = self.slots.len();
        let dim = 2 * n;
        if n == 0
            || n > 64
            || self.names.len() != n
            || self.declarations.len() != n
            || [
                self.q.len(),
                self.p.len(),
                self.damping.len(),
                self.input.len(),
            ]
            .iter()
            .any(|&l| l != n)
            || self.gradient.len() != dim
            || self.smooth_rate.len() != dim
            || self.interconnection.len() != dim * dim
            || self.slots.windows(2).any(|w| w[0] >= w[1])
        {
            return Err("invalid canonical projection dimensions or coordinate binding".into());
        }
        if self
            .q
            .iter()
            .chain(&self.p)
            .chain(&self.gradient)
            .chain(&self.smooth_rate)
            .chain(&self.interconnection)
            .chain(&self.input)
            .chain(&self.damping)
            .chain(&[
                self.energy,
                self.input_power,
                self.dissipated_power,
                self.balance_residual,
                self.velocity_residual,
            ])
            .any(|v| !v.is_finite())
            || self.damping.iter().any(|v| *v < 0.)
        {
            return Err("nonfinite or active-loss canonical projection".into());
        }
        let mut rate = vec![0.; dim];
        for (row, out) in rate.iter_mut().enumerate() {
            for column in 0..dim {
                let expected = if row < n && column == n + row {
                    1.
                } else if row >= n && column == row - n {
                    -1.
                } else {
                    0.
                };
                if self.interconnection[row * dim + column] != expected {
                    return Err("canonical signed pairing changed".into());
                }
                *out += self.interconnection[row * dim + column] * self.gradient[column];
            }
            if row >= n {
                *out += self.input[row - n] - self.damping[row - n] * self.gradient[row];
            }
        }
        let supplied: f64 = self
            .input
            .iter()
            .zip(&self.gradient[n..])
            .map(|(u, y)| u * y)
            .sum();
        let lost: f64 = self
            .damping
            .iter()
            .zip(&self.gradient[n..])
            .map(|(d, y)| d * y * y)
            .sum();
        let residual = self
            .gradient
            .iter()
            .zip(&rate)
            .map(|(e, f)| e * f)
            .sum::<f64>()
            - supplied
            + lost;
        let tolerance = 1e-10 * (1. + supplied.abs() + lost.abs());
        if rate
            .iter()
            .zip(&self.smooth_rate)
            .any(|(a, b)| (a - b).abs() > tolerance)
            || (self.input_power - supplied).abs() > tolerance
            || (self.dissipated_power - lost).abs() > tolerance
            || (self.balance_residual - residual).abs() > tolerance
            || residual.abs() > tolerance
        {
            return Err("canonical port power identity failed".into());
        }
        Ok(())
    }
}

impl PowerGraph {
    /// Canonical q/p port graph of a checked nonlinear mechanism, derived from
    /// its moving joint slots. Constraint impulses remain in the separate audit.
    pub fn canonical_mechanics(engine: &Engine, time: f64) -> Result<Self, String> {
        if !time.is_finite() {
            return Err("nonfinite observation time".into());
        }
        let mapping = MechanicalProjection::observe(engine)?;
        let mut out = Self::new(
            format!("{} / canonical q,p", engine.model().name),
            None,
            time,
            Some(mapping.energy),
        );
        out.supplied_power = Some(mapping.input_power);
        out.dissipated_power = Some(mapping.dissipated_power);
        out.audit = engine.energy_audit().cloned();
        for (i, &slot) in mapping.slots.iter().enumerate() {
            let joint = &engine.model().joints[slot];
            let linear = joint.joint_type == JointType::Prismatic;
            out.push(Node::scalar(
                format!("q{i}"),
                joint.did,
                format!("{} / q", joint.name),
                Some(mapping.q[i]),
                if linear { "m" } else { "rad" },
            ));
            out.push(Node::scalar(
                format!("p{i}"),
                joint.did,
                format!("{} / p", joint.name),
                Some(mapping.p[i]),
                if linear { "kg m/s" } else { "kg m²/s" },
            ));
            out.connect_identified(format!("q{i}"), format!("p{i}"), Some(joint.did), Some(1.));
        }
        out.equations = vec![
            Equation::new(
                "Kanonikus energia",
                "H(q,p) = ½ pᵀM(q)⁻¹p + V(q)",
                Some(mapping.energy),
                "J",
            ),
            Equation::new(
                "Port-Hamiltoni alak",
                "ẋ = (J − R)∇H + Gu; x=(q,p); J=[0,I;−I,0]; R=diag(0,D); G=[0;I]",
                None,
                "",
            ),
            Equation::new(
                "Portazonosság",
                "y = ∂H/∂p = q̇; P = uᵀy",
                Some(mapping.input_power),
                "W",
            ),
            Equation::new(
                "Viszkózus veszteség",
                "D = yᵀ diag(d) y ≥ 0",
                Some(mapping.dissipated_power),
                "W",
            ),
            Equation::new(
                "Sima mérleg maradéka",
                "∇Hᵀẋ − uᵀy + yᵀ diag(d) y",
                Some(mapping.balance_residual),
                "W",
            ),
        ];
        out.note="Checked regular articulated coordinates. Tensor generates canonical signed pairs; the physical H is nonlinear and coupled. The smooth vector field excludes constraint impulses.".into();
        out.equation_note="∂H/∂q: középső differencia rögzített p mellett, h=10⁻⁵ max(1,|q|). ∂H/∂p: az owner ellenőrzött tömegoperátor-megoldása. A sima portazonosság strukturális ellenőrzés; az impulzusmunka és az integráció maradéka külön mérés. A q/p csomópontok nem független energiatárolók; H általában csatolt.".into();
        out.mapping = Some(mapping);
        Ok(out)
    }
}
